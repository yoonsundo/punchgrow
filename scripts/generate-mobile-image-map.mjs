import { readdir, writeFile } from 'node:fs/promises';

const directory = new URL('../assets/creatures/mobile/', import.meta.url);
const files = (await readdir(directory)).filter((file) => /^PG-\d{3}\.png$/.test(file)).sort();
if (files.length !== 256) throw new Error(`Expected 256 mobile images, found ${files.length}`);

const rows = files.map((file) => {
  const id = file.slice(0, 6);
  return `  '${id}': require('../../assets/creatures/mobile/${file}'),`;
});
const source = `// Generated by scripts/generate-mobile-image-map.mjs.\n`+
  `export const creatureImages: Record<string, number> = {\n${rows.join('\n')}\n};\n`;
await writeFile(new URL('../src/mobile/creature-images.ts', import.meta.url), source);
console.log(JSON.stringify({ images: files.length }));
